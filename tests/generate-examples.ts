import fs from 'node:fs';
import {validateReportReadiness} from '../src/services/reportValidation';
import * as XLSX from 'xlsx';
import * as data from '../src/services/syntheticData';
import * as engine from '../src/services/accountingEngine';
import { exportFullFinancialWorkbookXLSX, exportExecutivePDF, csvCell } from '../src/services/exportService';
XLSX.set_fs(fs);
fs.mkdirSync('examples',{recursive:true});
const rows=engine.calculateAdjustedTrialBalance(data.SAMPLE_TB_FY2025,data.SAMPLE_ADJUSTMENTS_FY2025).adjustedRows;
const pnl=engine.generateProfitAndLoss(rows),bs=engine.generateBalanceSheet(rows,pnl.netProfit),eq=engine.generateChangesInEquity(data.SAMPLE_EQUITY_FY2025,pnl.netProfit,bs.equityItems);
const priorRows=engine.calculateAdjustedTrialBalance(data.SAMPLE_TB_FY2024,[]).adjustedRows;
const priorPnl=engine.generateProfitAndLoss(priorRows),priorBs=engine.generateBalanceSheet(priorRows,priorPnl.netProfit);
const cf=engine.generateIndirectCashFlow(bs,priorBs,pnl,data.SAMPLE_SUPPLEMENTARY_FY2025),ratios=engine.calculateFinancialRatios(bs,pnl);
fs.writeFileSync('examples/trial-balance.csv',['account_code,account_name,classification,is_contra,debit,credit',...data.SAMPLE_TB_FY2025.map(r=>[r.accountCode,r.accountName,r.classification,String(r.isContra),String(r.unadjustedDebit),String(r.unadjustedCredit)].map(csvCell).join(','))].join('\n'));
fs.writeFileSync('examples/transactions.json',JSON.stringify(data.SAMPLE_TRANSACTIONS,null,2));
fs.writeFileSync('examples/adjustments.json',JSON.stringify(data.SAMPLE_ADJUSTMENTS_FY2025,null,2));
fs.writeFileSync('examples/expected-results.json',JSON.stringify({pnl,bs,eq,cf},null,2));
const checks=validateReportReadiness(rows,bs,eq,data.SAMPLE_EQUITY_FY2025,priorBs,cf);
fs.writeFileSync('examples/opening-equity.json',JSON.stringify(data.SAMPLE_EQUITY_FY2025,null,2));
fs.writeFileSync('examples/cash-movements.json',JSON.stringify(data.SAMPLE_SUPPLEMENTARY_FY2025,null,2));
process.chdir('examples');
const period={...data.SAMPLE_PERIODS[0],name:'FY2025'};
exportFullFinancialWorkbookXLSX(data.SAMPLE_COMPANY,period,rows,pnl,bs,eq,cf,ratios,checks);
exportExecutivePDF(data.SAMPLE_COMPANY,period,pnl,bs,eq,cf,ratios,checks);
const workbook=XLSX.readFile('Apex_Horizon_Technologies_Inc._Financial_Statements_FY2025.xlsx');
if(workbook.SheetNames.length!==7) throw new Error('Expected seven statement worksheets');
console.log('PASS: Generated actual XLSX workbook and executive PDF; workbook reopened with all seven worksheets.');
